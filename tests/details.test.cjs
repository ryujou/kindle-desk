const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('playwright');
const base = process.env.KINDLE_PREVIEW_URL || 'http://127.0.0.1:18767';
(async () => {
    const browser = await chromium.launch({headless:true, executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
    const page = await browser.newPage({viewport:{width:1448,height:972}});
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    async function scenario(name, reload = false) {
        await page.request.get(base + '/scenario?name=' + name);
        if (reload || page.url() === 'about:blank') await page.goto(base);
        else {
            await page.waitForFunction(() => !document.getElementById('refresh').disabled);
            await page.locator('#refresh').click();
            await page.waitForFunction(() => !document.getElementById('refresh').disabled);
        }
        await page.waitForTimeout(250);
    }
    async function shot(name) { await page.screenshot({path:path.join(require('node:os').tmpdir(), 'kindle-details-' + name + '.png')}); }
    await scenario('plus');
    await page.locator('#ambient-weather').click();
    assert.equal(await page.locator('.forecast tbody tr').count(), 6);
    assert.equal(await page.locator('#data-panel').evaluate(e => getComputedStyle(e).visibility), 'hidden');
    assert.match(await page.locator('.weather-range').textContent(), /最高 25℃.*最低 17℃/);
    assert.match(await page.locator('#details-notice').textContent(), /演示数据/);
    assert.equal(await page.evaluate(() => DeskCompanion.pet.enabled), false);
    assert.equal(await page.locator('#details-content').evaluate(e => e.scrollHeight <= e.clientHeight + 1), true, 'six forecast rows fit');
    await shot('weather');
    await page.locator('#details-back').click();
    assert.equal(await page.evaluate(() => DeskCompanion.pet.enabled), true);
    await scenario('missing_weather');
    await page.locator('#ambient-weather').click();
    assert.match(await page.locator('#details-content').textContent(), /未提供/);
    assert.equal(await page.locator('.forecast').count(), 0);
    await page.locator('#details-back').click();
    await scenario('empty_weather', true);
    await page.locator('#ambient-weather').click();
    assert.match(await page.locator('#details-content').textContent(), /尚未收到天气/);
    await page.locator('#details-back').click();
    await scenario('long_task');
    await page.locator('#task-open').click();
    assert.match(await page.locator('.task-copy h3').textContent(), /Kindle/);
    assert.match(await page.locator('.task-message').textContent(), /公开任务进度/);
    assert.match(await page.locator('.task-quota').textContent(), /72%/);
    assert.equal(await page.locator('#details-content').evaluate(e => e.scrollHeight > e.clientHeight), true);
    await shot('task');
    await page.locator('#details-back').click();
    await page.locator('#other-task-open').click();
    assert.match(await page.locator('.task-quota').textContent(), /另一账号.*Pro/);
    assert.match(await page.locator('.task-quota').textContent(), /88%/);
    await page.locator('#details-back').click();
    await scenario('mismatch');
    await page.locator('#task-open').click();
    assert.equal(await page.locator('.detail-quota-row').count(), 0);
    assert.match(await page.locator('.task-quota').textContent(), /正在获取当前账号额度/);
    await page.locator('#details-back').click();
    await scenario('running');

    if (await page.locator('#pet').isVisible()) await page.locator('#pet').click();
    await scenario('waiting');
    assert.equal(await page.evaluate(() => DeskCompanion.pet.currentRow()), 6);
    assert.equal(await page.evaluate(() => DeskCompanion.pet.reactionRow), null);
    assert.match(await page.locator('#pet-message').textContent(), /确认/);
    await page.evaluate(() => {
        window.transitions = 0;
        const original = DeskCompanion.pet.setState;
        DeskCompanion.pet.setState = function (value) { if (value !== this.state) window.transitions++; return original.call(this, value); };
    });
    await scenario('waiting');
    assert.equal(await page.evaluate(() => window.transitions), 0, 'same event does not restart animation');
    if (await page.locator('#pet').isVisible()) await page.locator('#pet').click();
    assert.equal(await page.evaluate(() => DeskCompanion.pet.reactionRow), null, 'confirmation has priority over manual action');
    await scenario('review');
    assert.equal(await page.evaluate(() => DeskCompanion.pet.state), 'review');
    assert.match(await page.locator('#pet-message').textContent(), /完成/);
    await scenario('failed');
    assert.equal(await page.evaluate(() => DeskCompanion.pet.currentRow()), 5);
    await scenario('plus');
    const cpu = await page.locator('#cpu').textContent();
    await scenario('offline');
    assert.equal(await page.locator('#cpu').textContent(), cpu);
    assert.match(await page.locator('#connection').textContent(), /离线/);
    assert.equal(await page.locator('#room-temperature').textContent(), '24');
    assert.equal(await page.evaluate(() => DeskCompanion.pet.state), 'offline');
    await page.locator('#ambient-weather').click();
    assert.match(await page.locator('#details-notice').textContent(), /电脑离线/);
    assert.equal(await page.locator('.forecast tbody tr').count(), 6);
    await page.locator('#details-back').click();
    await scenario('stale');
    assert.match(await page.locator('#environment-age').textContent(), /过期/);
    await shot('stale');
    await page.locator('#task-open').click();
    assert.match(await page.locator('#details-notice').textContent(), /任务状态未同步/);
    assert.equal(await page.locator('.detail-quota-row').count(), 0);
    await page.locator('#details-back').click();
    await scenario('plus');
    assert.equal(await page.locator('#connection').textContent(), '电脑在线');
    await page.setViewportSize({width:1072,height:1448});
    await page.waitForTimeout(250);
    await page.locator('#ambient-weather').press('Enter');
    await shot('portrait');
    const bounds = await page.locator('#desk').boundingBox();
    assert.ok(bounds.x >= -1 && bounds.y >= -1 && bounds.x + bounds.width <= 1073 && bounds.y + bounds.height <= 1449);
    await page.locator('#details-back').click();
    await page.locator('#exit').click();
    let polls = 0; page.on('request', r => { if (r.url().includes('snapshot.sh')) polls++; });
    await page.waitForTimeout(3300);
    assert.equal(polls, 0); assert.equal(await page.evaluate(() => DeskCompanion.pet.enabled), false);
    await page.locator('#resume').click();
    await page.waitForTimeout(250);
    assert.ok(polls > 0);
    await scenario('offline', true);
    assert.equal(await page.locator('#cpu').textContent(), '—');
    await page.locator('#task-open').click();
    assert.match(await page.locator('.task-copy').textContent(), /尚未收到任务/);
    assert.deepEqual(errors, []);
    await browser.close();
    console.log('PASS: weather, missing fields, task details, account isolation, event priority, stale/offline/recovery, portrait, exit/resume and cold start.');
})().catch(error => { console.error(error); process.exit(1); });
